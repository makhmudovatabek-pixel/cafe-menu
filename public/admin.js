let adminLang = 'ru';
let data = null;
let expiresAt = 0;
let timerInterval = null;
let toastTimeout = null;
let editingDish = null;
let editingCategory = null;
const $ = (id) => document.getElementById(id);
const tr = (key) => adminCopy[adminLang][key] || key;
const localized = (value) => value && (value[adminLang] || value.kk || value.ru) || '';

async function api(url, options = {}) {
  const requestOptions = { method: options.method || 'GET', credentials: 'same-origin', headers: {} };
  if (options.body !== undefined) {
    requestOptions.headers['Content-Type'] = 'application/json';
    requestOptions.body = JSON.stringify(options.body);
  }
  const response = await fetch(url, requestOptions);
  const result = await response.json().catch(() => ({}));
  if (!response.ok) throw new Error(result.error || tr('requestFailed'));
  return result;
}

function setLanguage(language) {
  adminLang = language;
  localStorage.setItem('abdulla-ata-admin-language', language);
  document.documentElement.lang = language;
  document.querySelectorAll('[data-i18n]').forEach((element) => {
    const key = element.dataset.i18n;
    if (adminCopy[language][key]) element.textContent = adminCopy[language][key];
  });
  document.querySelectorAll('[data-admin-lang]').forEach((button) => {
    const active = button.dataset.adminLang === language;
    button.classList.toggle('is-active', active);
    button.setAttribute('aria-pressed', String(active));
  });
  if (data) {
    drawDishes();
    drawCategories();
    drawSlides();
  }
  if (editingDish) $('dishDialogTitle').textContent = editingDish.id ? tr('editDish') : tr('newDish');
  if (editingCategory !== null) $('categoryDialogTitle').textContent = editingCategory ? tr('editCategory') : tr('newCategory');
}

function showLogin(message = '') {
  $('loginView').hidden = false;
  $('adminView').hidden = true;
  $('sessionControls').hidden = true;
  $('loginError').textContent = message;
  $('loginError').hidden = !message;
  if (timerInterval) clearInterval(timerInterval);
  timerInterval = null;
}

function showAdmin(session) {
  expiresAt = session.expiresAt;
  $('loginView').hidden = true;
  $('adminView').hidden = false;
  $('sessionControls').hidden = false;
  updateTimer();
  if (timerInterval) clearInterval(timerInterval);
  timerInterval = setInterval(updateTimer, 1000);
}

function updateTimer() {
  const remaining = Math.max(0, Math.floor((expiresAt - Date.now()) / 1000));
  const minutes = String(Math.floor(remaining / 60)).padStart(2, '0');
  const seconds = String(remaining % 60).padStart(2, '0');
  $('sessionTimer').textContent = `${minutes}:${seconds}`;
  if (remaining === 0) {
    showLogin(tr('sessionEnded'));
    api('/api/admin/logout', { method: 'POST' }).catch(() => {});
  }
}

function showToast(message) {
  const toast = $('toast');
  toast.textContent = message;
  toast.hidden = false;
  clearTimeout(toastTimeout);
  toastTimeout = setTimeout(() => { toast.hidden = true; }, 3400);
}

function setTab(name) {
  document.querySelectorAll('.admin-tab').forEach((button) => {
    const active = button.dataset.tab === name;
    button.classList.toggle('is-active', active);
    button.setAttribute('aria-selected', String(active));
  });
  for (const panel of ['dishes', 'categories', 'slides']) $(panel + 'Panel').hidden = panel !== name;
}

function price(value) {
  return `${Number(value).toLocaleString(adminLang === 'kk' ? 'kk-KZ' : 'ru-KZ')} ₸`;
}

function drawDishes() {
  const list = $('dishList');
  list.replaceChildren();
  $('noDishes').hidden = data.dishes.length > 0;
  const categoryById = new Map(data.categories.map((category) => [category.id, category]));
  data.dishes.forEach((dish) => {
    const row = document.createElement('article');
    row.className = `dish-admin-row${dish.isAvailable === false ? ' is-unavailable' : ''}`;
    const image = document.createElement('img');
    image.src = dish.image;
    image.alt = localized(dish.name);
    image.loading = 'lazy';
    const info = document.createElement('div');
    info.className = 'dish-admin-info';
    const title = document.createElement('strong');
    title.textContent = localized(dish.name);
    const details = document.createElement('small');
    details.textContent = `${localized(categoryById.get(dish.categoryId)?.names) || tr('noCategory')} · ${localized(dish.description)}`;
    info.append(title, details);
    const cost = document.createElement('span');
    cost.className = 'dish-admin-price';
    cost.textContent = price(dish.price);
    const actions = document.createElement('div');
    actions.className = 'dish-admin-actions';
    const availabilityLabel = document.createElement('label');
    availabilityLabel.className = 'availability-toggle';
    const availability = document.createElement('input');
    availability.type = 'checkbox';
    availability.checked = dish.isAvailable === false;
    availability.setAttribute('aria-label', `${tr('unavailableToggle')}: ${localized(dish.name)}`);
    const availabilityText = document.createElement('span');
    availabilityText.textContent = tr('unavailableToggle');
    availabilityLabel.append(availability, availabilityText);
    availability.addEventListener('change', async () => {
      const isUnavailable = availability.checked;
      availability.disabled = true;
      try {
        await api(`/api/admin/dishes/${encodeURIComponent(dish.id)}/availability`, {
          method: 'PATCH',
          body: { isAvailable: !isUnavailable }
        });
        await reloadData();
        showToast(isUnavailable ? tr('dishHidden') : tr('dishRestored'));
      } catch (error) {
        availability.checked = !isUnavailable;
        availability.disabled = false;
        showToast(error.message || tr('requestFailed'));
      }
    });
    const edit = document.createElement('button');
    edit.type = 'button';
    edit.className = 'button button-quiet edit-dish';
    edit.textContent = tr('edit');
    edit.addEventListener('click', () => openDish(dish));
    actions.append(availabilityLabel, edit);
    row.append(image, info, cost, actions);
    list.append(row);
  });
}

function drawCategories() {
  const list = $('categoryList');
  list.replaceChildren();
  data.categories.forEach((category) => {
    const card = document.createElement('article');
    card.className = 'category-admin-card';
    const info = document.createElement('div');
    const ru = document.createElement('strong');
    ru.textContent = category.names.ru;
    info.append(ru);
    const actions = document.createElement('div');
    actions.className = 'category-actions';
    const edit = document.createElement('button');
    edit.type = 'button';
    edit.className = 'button button-quiet';
    edit.textContent = tr('edit');
    edit.addEventListener('click', () => openCategory(category));
    const remove = document.createElement('button');
    remove.type = 'button';
    remove.className = 'button button-danger';
    remove.textContent = tr('delete');
    remove.addEventListener('click', () => deleteCategory(category));
    actions.append(edit, remove);
    card.append(info, actions);
    list.append(card);
  });
}

function drawSlides() {
  const list = $('slideList');
  list.replaceChildren();
  data.slides.slice(0, 2).forEach((slide, index) => {
    const card = document.createElement('article');
    card.className = 'slide-admin-card';
    const image = document.createElement('img');
    image.src = slide.image;
    image.alt = localized(slide.alt);
    const controls = document.createElement('div');
    controls.className = 'slide-admin-controls';
    const label = document.createElement('label');
    label.textContent = `${tr('slideLabel')} ${index + 1}`;
    const input = document.createElement('input');
    input.type = 'file';
    input.accept = 'image/png,image/jpeg,image/webp';
    input.setAttribute('aria-label', tr('uploadSlide'));
    input.addEventListener('change', () => {
      const file = input.files?.[0];
      if (file) image.src = URL.createObjectURL(file);
    });
    label.append(input);
    const save = document.createElement('button');
    save.type = 'button';
    save.className = 'button button-primary';
    save.textContent = tr('saveSlide');
    save.addEventListener('click', () => saveSlide(index, input.files?.[0]));
    controls.append(label, save);
    card.append(image, controls);
    list.append(card);
  });
}

function fillDishCategories(selectedId = '') {
  const select = $('dishCategory');
  select.replaceChildren();
  data.categories.forEach((category) => {
    const option = document.createElement('option');
    option.value = category.id;
    option.textContent = category.names.ru;
    option.selected = category.id === selectedId;
    select.append(option);
  });
  $('addDishButton').disabled = data.categories.length === 0;
  $('addDishButton').title = data.categories.length === 0 ? tr('categoryRequired') : '';
}

function openDish(dish = null) {
  editingDish = dish;
  $('dishDialogTitle').textContent = dish ? tr('editDish') : tr('newDish');
  $('dishId').value = dish?.id || '';
  $('dishNameKk').value = dish?.name.kk || '';
  $('dishNameRu').value = dish?.name.ru || '';
  $('dishDescriptionKk').value = dish?.description.kk || '';
  $('dishDescriptionRu').value = dish?.description.ru || '';
  $('dishPrice').value = dish?.price ?? '';
  $('dishIsNew').checked = Boolean(dish?.isNew);
  $('dishImageFile').value = '';
  $('dishImageFile').required = !dish;
  $('dishImageFile').dataset.currentImage = dish?.image || '';
  const preview = $('dishImagePreview');
  preview.src = dish?.image || '';
  preview.hidden = !dish?.image;
  $('dishError').hidden = true;
  fillDishCategories(dish?.categoryId || data.categories[0]?.id || '');
  if (data.categories.length === 0) return showToast(tr('categoryRequired'));
  $('dishDialog').showModal();
}

function openCategory(category = null) {
  editingCategory = category;
  $('categoryDialogTitle').textContent = category ? tr('editCategory') : tr('newCategory');
  $('categoryId').value = category?.id || '';
  $('categoryNameKk').value = category?.names.kk || '';
  $('categoryNameRu').value = category?.names.ru || '';
  $('categoryError').hidden = true;
  $('categoryDialog').showModal();
}

function readFile(file) {
  return new Promise((resolve, reject) => {
    const reader = new FileReader();
    reader.onload = () => resolve(reader.result);
    reader.onerror = () => reject(new Error(tr('uploadError')));
    reader.readAsDataURL(file);
  });
}

async function uploadImage(file) {
  if (!file) throw new Error(tr('imageRequired'));
  if (file.size > 5 * 1024 * 1024) throw new Error(tr('imageTooLarge'));
  const allowed = ['image/png', 'image/jpeg', 'image/webp'];
  if (!allowed.includes(file.type)) throw new Error(tr('uploadError'));
  const dataUrl = await readFile(file);
  const result = await api('/api/admin/upload', { method: 'POST', body: { dataUrl } });
  return result.image;
}

async function reloadData() {
  data = await api('/api/admin/menu');
  drawDishes();
  drawCategories();
  drawSlides();
}

async function deleteCategory(category) {
  if (!window.confirm(tr('deleteCategoryConfirm'))) return;
  try {
    await api(`/api/admin/categories/${encodeURIComponent(category.id)}`, { method: 'DELETE' });
    await reloadData();
    showToast(tr('categoryDeleted'));
  } catch (error) {
    showToast(error.message);
  }
}

async function saveSlide(index, file) {
  if (!file) return showToast(tr('imageRequired'));
  try {
    const image = await uploadImage(file);
    await api(`/api/admin/slides/${index}`, { method: 'PUT', body: { image, alt: data.slides[index].alt } });
    await reloadData();
    showToast(tr('slideSaved'));
  } catch (error) {
    showToast(error.message || tr('uploadError'));
  }
}

